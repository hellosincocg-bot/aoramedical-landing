\set QUIET on
set check_function_bodies = off;
set client_min_messages = warning;

-- compatibilidad: Neon expone auth.user_id() (text); en Supabase se deriva de auth.uid()
create or replace function auth.user_id() returns text
language sql stable as $f$ select nullif(auth.uid()::text, '') $f$;
grant execute on function auth.user_id() to anon, authenticated, service_role;

select migracion.dblink_connect('neon', :'neon_conn');

drop table if exists migracion.stmts;
create table migracion.stmts as
select * from migracion.dblink('neon', $q$
  -- 20: tablas (sin defaults; las columnas identidad crean su propia secuencia)
  select 20 ord, c.relname::text sub,
    'create table public.'||quote_ident(c.relname)||' ('||
    (select string_agg(quote_ident(a.attname)||' '||format_type(a.atttypid,a.atttypmod)||
        case a.attidentity when 'a' then ' generated always as identity' when 'd' then ' generated by default as identity' else '' end||
        case when a.attnotnull then ' not null' else '' end, ', ' order by a.attnum)
       from pg_attribute a where a.attrelid=c.oid and a.attnum>0 and not a.attisdropped)||')' stmt
  from pg_class c join pg_namespace n on n.oid=c.relnamespace
  where n.nspname='public' and c.relkind='r'
  union all
  -- 30: funciones propias (no de extensiones, sin las 7 que dependen de neon_auth)
  select 30, f.nm,
    case when f.d ~ 'crypt\(|gen_salt|digest\(|hmac\(|gen_random_bytes|pgp_'
         then replace(f.d, 'SET search_path TO ''public'', ''pg_temp''', 'SET search_path TO ''public'', ''extensions'', ''pg_temp''')
         else f.d end
  from (select p.proname||'('||pg_get_function_identity_arguments(p.oid)||')' nm, pg_get_functiondef(p.oid) d
        from pg_proc p join pg_namespace n on n.oid=p.pronamespace
        where n.nspname='public' and p.prokind='f'
          and not exists (select 1 from pg_depend dp where dp.objid=p.oid and dp.deptype='e')) f
  where f.d !~ 'neon_auth'
  union all
  -- 40: defaults
  select 40, c.relname||'.'||a.attname,
    'alter table public.'||quote_ident(c.relname)||' alter column '||quote_ident(a.attname)||' set default '||pg_get_expr(d.adbin,d.adrelid)
  from pg_attrdef d join pg_class c on c.oid=d.adrelid join pg_namespace n on n.oid=c.relnamespace
  join pg_attribute a on a.attrelid=d.adrelid and a.attnum=d.adnum
  where n.nspname='public' and c.relkind='r' and a.attidentity=''
  union all
  -- 50: claves primarias, unicas, check y exclusion
  select 50, c.relname||'.'||co.conname,
    'alter table public.'||quote_ident(c.relname)||' add constraint '||quote_ident(co.conname)||' '||pg_get_constraintdef(co.oid)
  from pg_constraint co join pg_class c on c.oid=co.conrelid join pg_namespace n on n.oid=c.relnamespace
  where n.nspname='public' and c.relkind='r' and co.contype in ('p','u','c','x')
  union all
  -- 55: claves foraneas
  select 55, c.relname||'.'||co.conname,
    'alter table public.'||quote_ident(c.relname)||' add constraint '||quote_ident(co.conname)||' '||pg_get_constraintdef(co.oid)
  from pg_constraint co join pg_class c on c.oid=co.conrelid join pg_namespace n on n.oid=c.relnamespace
  where n.nspname='public' and c.relkind='r' and co.contype='f'
  union all
  -- 60: indices que no respaldan una restriccion
  select 60, ic.relname, pg_get_indexdef(i.indexrelid)
  from pg_index i join pg_class ic on ic.oid=i.indexrelid join pg_class c on c.oid=i.indrelid join pg_namespace n on n.oid=c.relnamespace
  where n.nspname='public' and c.relkind='r' and not i.indisprimary
    and not exists (select 1 from pg_constraint co where co.conindid=i.indexrelid)
  union all
  -- 70: triggers
  select 70, c.relname||'.'||t.tgname, pg_get_triggerdef(t.oid)
  from pg_trigger t join pg_class c on c.oid=t.tgrelid join pg_namespace n on n.oid=c.relnamespace
  where n.nspname='public' and not t.tgisinternal
  union all
  -- 80: RLS
  select 80, c.relname,
    'alter table public.'||quote_ident(c.relname)||' enable row level security'||case when c.relforcerowsecurity then '; alter table public.'||quote_ident(c.relname)||' force row level security' else '' end
  from pg_class c join pg_namespace n on n.oid=c.relnamespace
  where n.nspname='public' and c.relkind='r' and c.relrowsecurity
  union all
  -- 85: politicas
  select 85, tablename||'.'||policyname,
    'create policy '||quote_ident(policyname)||' on public.'||quote_ident(tablename)||' as '||lower(permissive)||' for '||lower(cmd)||
    ' to '||(select string_agg(case r when 'anonymous' then 'anon' else quote_ident(r) end, ', ') from unnest(roles) r)||
    coalesce(' using ('||qual||')','')||coalesce(' with check ('||with_check||')','')
  from pg_policies where schemaname='public'
  union all
  -- 90: permisos de tablas (solo roles de API)
  select 90, c.relname||'.'||g.rol, 'grant '||g.priv||' on table public.'||quote_ident(c.relname)||' to '||g.rol
  from pg_class c join pg_namespace n on n.oid=c.relnamespace
  cross join lateral (select a.privilege_type priv,
        case when a.grantee=0 then 'public' when r.rolname='anonymous' then 'anon' else r.rolname end rol
      from aclexplode(c.relacl) a left join pg_roles r on r.oid=a.grantee) g
  where n.nspname='public' and c.relkind='r' and g.rol in ('anon','authenticated','public')
  union all
  -- 95: permisos de ejecucion de funciones
  select 95, f.nm||'.'||g.rol, 'grant execute on function '||f.sig||' to '||g.rol
  from (select p.oid, p.proname||'('||pg_get_function_identity_arguments(p.oid)||')' nm,
               'public.'||quote_ident(p.proname)||'('||pg_get_function_identity_arguments(p.oid)||')' sig,
               p.proacl, pg_get_functiondef(p.oid) d
        from pg_proc p join pg_namespace n on n.oid=p.pronamespace
        where n.nspname='public' and p.prokind='f'
          and not exists (select 1 from pg_depend dp where dp.objid=p.oid and dp.deptype='e')) f
  cross join lateral (
      select case when a.grantee=0 then 'public' when r.rolname='anonymous' then 'anon' else r.rolname end rol
      from aclexplode(f.proacl) a left join pg_roles r on r.oid=a.grantee
      where a.privilege_type='EXECUTE'
      union all select 'public' where f.proacl is null) g
  where f.d !~ 'neon_auth' and g.rol in ('anon','authenticated','public')
$q$) as t(ord int, sub text, stmt text);

\echo '--- sentencias generadas por etapa (ord: 20 tablas, 30 funciones, 40 defaults, 50 pk/uq/ck, 55 fk, 60 indices, 70 triggers, 80 rls, 85 politicas, 90 grants tablas, 95 grants funciones) ---'
select ord, count(*) from migracion.stmts group by 1 order by 1;

-- Supabase da todo a anon/authenticated por defecto: se limpia y se reaplica lo que tenia Neon
select stmt from migracion.stmts where ord < 90 order by ord, sub \gexec

revoke all on all tables in schema public from anon, authenticated;
revoke all on all functions in schema public from public, anon, authenticated;
revoke all on all sequences in schema public from anon, authenticated;

select stmt from migracion.stmts where ord >= 90 order by ord, sub \gexec

\echo '--- resultado en Supabase ---'
select (select count(*) from information_schema.tables where table_schema='public' and table_type='BASE TABLE') tablas,
       (select count(*) from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname='public' and p.prokind='f'
          and not exists (select 1 from pg_depend dp where dp.objid=p.oid and dp.deptype='e')) funciones,
       (select count(*) from pg_policies where schemaname='public') politicas,
       (select count(*) from pg_indexes where schemaname='public') indices,
       (select count(*) from pg_trigger t join pg_class c on c.oid=t.tgrelid join pg_namespace n on n.oid=c.relnamespace where n.nspname='public' and not t.tgisinternal) triggers,
       (select count(*) from pg_constraint co join pg_namespace n on n.oid=co.connamespace where n.nspname='public' and co.contype in ('p','u','c','x','f')) restricciones;
